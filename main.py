@app.post("/api/projects/analyze-upload")
async def analyze_upload(request: Request, file: UploadFile = File(...)):
    data = await file.read(MAX_UPLOAD + 1)
    if len(data) > MAX_UPLOAD:
        raise HTTPException(413, f"Upload exceeds {MAX_UPLOAD // (1024*1024)} MB limit.")
    topic = extract_text(file.filename or "upload.txt", data).strip()
    if len(topic) < 5:
        raise HTTPException(400, "No readable text was extracted from this file.")
    return {"filename": file.filename, "topic": topic[:20000]}

@app.post("/api/projects/generate")
async def generate(body: GenerateRequest, request: Request):
    result = await call_ai(body.topic, body.language, body.framework, safe_name(body.project_name))
    try:
        file_map = sanitize_files(result.get("files", {}))
    except ValueError as e:
        raise HTTPException(502, str(e))
    pid = str(uuid.uuid4())
    sid = session_id(request)
    name = safe_name(body.project_name)
    projects[pid] = {"id":pid, "owner":sid, "name":name, "files":file_map,
                     "summary":result.get("summary",""), "architecture":result.get("architecture",[]),
                     "created_at":time.time()}
    sessions[sid]["projects"].add(pid)
    return {"project_id":pid, "name":name, "summary":projects[pid]["summary"],
            "architecture":projects[pid]["architecture"], "files":[{"path":p,"size":len(c.encode())} for p,c in file_map.items()]}

