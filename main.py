@app.post("/api/github/publish")
async def github_publish(body: PublishRequest, request: Request):
    if not body.confirm: raise HTTPException(400, "Explicit confirmation is required before publishing.")
    p = owned_project(request, body.project_id)
    s = sessions.get(session_id(request), {})
    token = s.get("github_token")
    if not token: raise HTTPException(401, "Connect GitHub first.")
    repo_name = safe_name(body.repo_name)
    if body.mode == "create":
        repo = await gh_request(token, "POST", "/user/repos", json={
            "name":repo_name,"description":body.description,"private":body.private,"auto_init":True})
    elif body.mode == "existing":
        # Existing repository name may be owner/repo; only allow the connected user's repositories.
        if "/" in body.repo_name:
            owner, repo_name = body.repo_name.split("/",1)
            if owner.lower() != (s.get("github_login") or "").lower():
                raise HTTPException(403, "Publishing is restricted to repositories owned by the connected account.")
        else:
            owner = s.get("github_login")
        repo = await gh_request(token, "GET", f"/repos/{owner}/{repo_name}")
    else:
        raise HTTPException(400, "mode must be 'create' or 'existing'.")
    owner = repo["owner"]["login"]
    branch = body.branch.strip() or repo.get("default_branch") or "main"
    # Ensure branch exists; newly created repositories may be initializing.
    ref = None
    for _ in range(5):
        try:
            ref = await gh_request(token, "GET", f"/repos/{owner}/{repo_name}/git/ref/heads/{branch}")
            break
        except HTTPException as e:
            if e.status_code == 404:
                await __import__("asyncio").sleep(1)
            else: raise
    if not ref:
        # For an empty/new repository, initialize by creating the first file via Contents API.
        first_path, first_content = next(iter(p["files"].items()))
        first_path = clean_path(first_path)
        await gh_request(token, "PUT", f"/repos/{owner}/{repo_name}/contents/{first_path}",
            json={"message":"Add generated project files","content":base64.b64encode(first_content.encode()).decode(),"branch":branch})
    else:
        # Use Git Data API to commit all generated files atomically.
        commit = await gh_request(token, "GET", f"/repos/{owner}/{repo_name}/git/ref/heads/{branch}")
        base_commit = await gh_request(token, "GET", f"/repos/{owner}/{repo_name}/git/commits/{commit['object']['sha']}")
        tree_items = []
        for path, content in p["files"].items():
            try: path = clean_path(path)
            except ValueError: continue
            if path.lower().startswith(".env") and path.lower() != ".env.example": continue
            blob = await gh_request(token, "POST", f"/repos/{owner}/{repo_name}/git/blobs",
                json={"content":content,"encoding":"utf-8"})
            tree_items.append({"path":path,"mode":"100644","type":"blob","sha":blob["sha"]})
        tree = await gh_request(token, "POST", f"/repos/{owner}/{repo_name}/git/trees",
            json={"base_tree":base_commit["tree"]["sha"],"tree":tree_items})
        new_commit = await gh_request(token, "POST", f"/repos/{owner}/{repo_name}/git/commits",
            json={"message":"Publish generated project","tree":tree["sha"],"parents":[base_commit["sha"]]})
        await gh_request(token, "PATCH", f"/repos/{owner}/{repo_name}/git/refs/heads/{branch}",
            json={"sha":new_commit["sha"],"force":False})
    return {"success":True,"repository_url":repo.get("html_url",f"https://github.com/{owner}/{repo_name}"),
            "branch":branch,"files_published":len(p["files"]),"message":"GitHub confirmed the publish request."}

