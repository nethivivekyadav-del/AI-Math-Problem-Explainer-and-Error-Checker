@app.get("/api/projects/{project_id}/download")
def download(project_id: str, request: Request):
    p = owned_project(request, project_id)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for path, content in p["files"].items():
            try: clean_path(path)
            except ValueError: continue
            if path.lower().startswith(".env") and path.lower() != ".env.example": continue
            z.writestr(f"{p['name']}/{path}", content)
    buf.seek(0)
    return StreamingResponse(buf, media_type="application/zip",
        headers={"Content-Disposition": f'attachment; filename="{p["name"]}.zip"'})

