def safe_name(name: str) -> str:
    name = re.sub(r"[^A-Za-z0-9._-]+", "-", name.strip()).strip(".-")
    return (name or "generated-project")[:80]

def session_id(request: Request) -> str:
    sid = request.session.get("sid")
    if not sid:
        sid = secrets.token_urlsafe(32)
        request.session["sid"] = sid
    sessions.setdefault(sid, {"github_token": None, "github_login": None, "projects": set()})
    return sid

def owned_project(request: Request, project_id: str):
    sid = session_id(request)
    project = projects.get(project_id)
    if not project or project["owner"] != sid:
        raise HTTPException(404, "Project not found for this session.")
    return project

def clean_path(path: str) -> str:
    path = path.replace("\\\\", "/").lstrip("/")
    parts = Path(path).parts
    if not path or path.startswith("/") or any(p in ("..", ".") for p in parts):
        raise ValueError("Unsafe file path")
    if any(x.lower() in {".env", ".env.local", ".env.production", "id_rsa"} for x in parts):
        raise ValueError("Secret-like files are not allowed")
    return path

def sanitize_files(raw_files):
    if not isinstance(raw_files, dict) or not raw_files:
        raise ValueError("AI returned no files")
    output = {}
    for raw_path, content in raw_files.items():
        path = clean_path(str(raw_path))
        if path.lower().endswith((".pyc", ".pyo")) or any(x in path.split("/") for x in ("node_modules", ".git", "__pycache__", "dist", "build")):
            continue
        if path.lower() in {".env", ".env.local", ".env.production"}:
            continue
        if not isinstance(content, str):
            content = json.dumps(content, indent=2)
        # Never accept real credentials in generated files; example files may contain placeholders.
        if re.search(r'(?i)(sk-[A-Za-z0-9]{20,}|gh[pousr]_[A-Za-z0-9]{20,})', content):
            content = re.sub(r'(?i)(sk-[A-Za-z0-9]{20,}|gh[pousr]_[A-Za-z0-9]{20,})', '[REDACTED_SECRET]', content)
        output[path] = content[:300000]
    output.setdefault("README.md", "# Generated Project\\n\\nGenerated by AI Project Builder. Review and test before use.\\n")
    output.setdefault(".gitignore", ".env\\n.env.*\\n!.env.example\\n__pycache__/\\n*.py[cod]\\nnode_modules/\\ndist/\\nbuild/\\n.venv/\\n")
    output.setdefault(".env.example", "# Add required environment variables here using placeholders only.\\n")
    return output

def extract_text(filename: str, data: bytes) -> str:
    ext = Path(filename.lower()).suffix
    if ext == ".txt" or ext == ".md":
        return data.decode("utf-8", errors="replace")
    if ext == ".pdf":
        try:
            from pypdf import PdfReader
            reader = PdfReader(io.BytesIO(data))
            return "\\n".join((p.extract_text() or "") for p in reader.pages)
        except Exception as e:
            raise HTTPException(400, f"Could not read PDF. Install pypdf; details: {e}")
    if ext == ".docx":
        try:
            from docx import Document
            doc = Document(io.BytesIO(data))
            return "\\n".join(p.text for p in doc.paragraphs)
        except Exception as e:
            raise HTTPException(400, f"Could not read DOCX. Install python-docx; details: {e}")
    if ext in {".png", ".jpg", ".jpeg", ".webp", ".bmp"}:
        try:
            from PIL import Image
            import pytesseract
            return pytesseract.image_to_string(Image.open(io.BytesIO(data)))
        except Exception:
            raise HTTPException(400, "Image OCR needs Pillow, pytesseract, and the Tesseract OCR system binary.")
    raise HTTPException(415, "Supported files: PDF, DOCX, TXT, MD, PNG, JPG, JPEG, WEBP.")

async def call_ai(topic: str, language: str, framework: str, project_name: str, analyze_only=False):
    if not AI_API_KEY:
        raise HTTPException(503, "AI provider is not configured. Set AI_API_KEY in backend/.env.")
    system = (
      "You are a senior software engineer. Generate safe, coherent, runnable starter projects. "
      "Never include real credentials, .env files, private keys, or destructive commands. "
      "Do not generate malware, credential theft, or exploit automation. "
      "Return ONLY valid JSON with keys: summary (string), architecture (array of strings), "
      "files (object mapping relative file paths to complete UTF-8 text contents). "
      "For analysis-only, files may be an empty object. Keep file paths relative and safe. "
      "Include README.md, .gitignore, .env.example, dependency manifests, and tests when appropriate."
    )
    if analyze_only:
        user = f"Analyze this project specification. Do not generate code; files must be {{}}.\\nTopic: {topic}\\nLanguage: {language}\\nFramework: {framework}"
    else:
        user = f"Generate a complete starter codebase. Project name: {project_name}. Language: {language}. Framework: {framework}.\\nSpecification:\\n{topic}\\n\\nInclude frontend/backend/database/API integrations only where useful. Include setup and testing instructions. Avoid fake credentials. Keep implementation reasonably complete and consistent."
    payload = {"model": AI_MODEL, "temperature": 0.2, "response_format": {"type": "json_object"},
               "messages": [{"role":"system","content":system},{"role":"user","content":user}]}
    try:
        async with httpx.AsyncClient(timeout=180) as client:
            r = await client.post(f"{AI_BASE_URL}/chat/completions", json=payload,
                                  headers={"Authorization": f"Bearer {AI_API_KEY}", "Content-Type":"application/json"})
        if r.status_code >= 400:
            raise HTTPException(502, f"AI provider returned HTTP {r.status_code}: {r.text[:500]}")
        content = r.json()["choices"][0]["message"]["content"]
        result = json.loads(content)
        if not isinstance(result, dict):
            raise ValueError("Expected JSON object")
        result.setdefault("summary", "Project generated from the supplied requirements.")
        result.setdefault("architecture", [])
        result.setdefault("files", {})
        return result
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(502, f"AI generation failed: {str(e)[:300]}")

