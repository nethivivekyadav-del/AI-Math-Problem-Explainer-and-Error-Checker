@app.get("/api/github/login")
def github_login(request: Request):
    if not GITHUB_CLIENT_ID or not GITHUB_CLIENT_SECRET:
        raise HTTPException(503, "Configure GITHUB_CLIENT_ID and GITHUB_CLIENT_SECRET in backend/.env first.")
    sid = session_id(request)
    state = secrets.token_urlsafe(32)
    oauth_states[state] = {"sid":sid, "expires":time.time()+600}
    params = {"client_id":GITHUB_CLIENT_ID, "redirect_uri":GITHUB_REDIRECT_URI,
              "scope":"repo", "state":state, "allow_signup":"true"}
    return RedirectResponse("https://github.com/login/oauth/authorize?"+urlencode(params))

@app.get("/api/github/callback")
async def github_callback(request: Request, code: str = "", state: str = "", error: str = ""):
    entry = oauth_states.pop(state, None)
    if error or not entry or entry["expires"] < time.time() or entry["sid"] != session_id(request):
        return RedirectResponse(FRONTEND_URL + "/?github=error")
    async with httpx.AsyncClient(timeout=20) as client:
        token_r = await client.post("https://github.com/login/oauth/access_token",
            headers={"Accept":"application/json"}, json={"client_id":GITHUB_CLIENT_ID,
            "client_secret":GITHUB_CLIENT_SECRET,"code":code,"redirect_uri":GITHUB_REDIRECT_URI})
        if token_r.status_code >= 400:
            return RedirectResponse(FRONTEND_URL + "/?github=error")
        token_data = token_r.json()
        token = token_data.get("access_token")
        if not token:
            return RedirectResponse(FRONTEND_URL + "/?github=error")
        user_r = await client.get("https://api.github.com/user", headers={"Authorization":f"Bearer {token}","Accept":"application/vnd.github+json"})
        if user_r.status_code >= 400:
            return RedirectResponse(FRONTEND_URL + "/?github=error")
        user = user_r.json()
    sessions[entry["sid"]]["github_token"] = token
    sessions[entry["sid"]]["github_login"] = user.get("login")
    return RedirectResponse(FRONTEND_URL + "/?github=connected")

async def gh_request(token, method, path, **kwargs):
    headers = kwargs.pop("headers", {})
    headers.update({"Authorization":f"Bearer {token}","Accept":"application/vnd.github+json",
                    "X-GitHub-Api-Version":"2022-11-28"})
    async with httpx.AsyncClient(timeout=60) as client:
        r = await client.request(method, "https://api.github.com"+path, headers=headers, **kwargs)
    if r.status_code == 401:
        raise HTTPException(401, "GitHub authorization expired. Connect GitHub again.")
    if r.status_code == 403 and r.headers.get("X-RateLimit-Remaining") == "0":
        raise HTTPException(429, "GitHub API rate limit reached. Try again later.")
    if r.status_code >= 400:
        raise HTTPException(r.status_code, f"GitHub API error ({r.status_code}): {r.text[:500]}")
    return r.json() if r.content else {}

@app.get("/api/github/repositories")
async def github_repositories(request: Request):
    s = sessions.get(session_id(request), {})
